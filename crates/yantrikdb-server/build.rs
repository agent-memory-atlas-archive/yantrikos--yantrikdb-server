//! Embeds the Studio web app (`studio/`) into the binary.
//!
//! Walks `studio/index.html` + `studio/assets/**` and emits a static table
//! (`$OUT_DIR/studio_assets.rs`) of `(path, content-type, bytes)`. Generating
//! it means a new frontend file can never be forgotten in a hand-maintained
//! list, and the server stays a single self-contained, air-gap-friendly binary
//! with no Node toolchain in the build.

use std::env;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

fn content_type(path: &Path) -> &'static str {
    match path.extension().and_then(|e| e.to_str()) {
        Some("html") => "text/html; charset=utf-8",
        Some("js") | Some("mjs") => "text/javascript; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("json") | Some("map") => "application/json",
        Some("svg") => "image/svg+xml",
        Some("png") => "image/png",
        Some("woff2") => "font/woff2",
        Some("ico") => "image/x-icon",
        _ => "application/octet-stream",
    }
}

fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            walk(&path, out);
        } else {
            out.push(path);
        }
    }
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let studio = manifest.join("studio");
    // Cargo rescans a directory recursively for this directive.
    println!("cargo:rerun-if-changed=studio");
    println!("cargo:rerun-if-changed=build.rs");

    let mut files = vec![studio.join("index.html")];
    walk(&studio.join("assets"), &mut files);
    files.sort();

    let out_path = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("studio_assets.rs");
    let mut out = fs::File::create(&out_path).expect("create studio_assets.rs");
    writeln!(out, "// @generated by build.rs — do not edit.").unwrap();
    writeln!(out, "pub static ASSETS: &[(&str, &str, &[u8])] = &[").unwrap();
    for file in &files {
        let rel = file
            .strip_prefix(&studio)
            .expect("under studio/")
            .to_string_lossy()
            .replace('\\', "/");
        let abs = file.to_string_lossy().replace('\\', "/");
        writeln!(out, "    ({rel:?}, {:?}, include_bytes!({abs:?})),", content_type(file)).unwrap();
    }
    writeln!(out, "];").unwrap();
}
